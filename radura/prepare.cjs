const fs=require('node:fs'),path=require('node:path');
const source=process.argv[2],destination=process.argv[3];
fs.mkdirSync(destination,{recursive:true});
const read=(folder,name)=>JSON.parse(fs.readFileSync(path.join(folder,name+'.json')));
const store=(key,data)=>fs.writeFileSync(path.join(destination,key+'.webp'),Buffer.from(data,'base64'));
for(const [key,data] of Object.entries(read(__dirname,'scene')))store(key,data);
const actor=read(source,'actors-hd'),materials=read(source,'staircase'),objects=read(source,'storybook');
for(const [key,data] of Object.entries(actor))if(/^walk[0-4][0-3]$/.test(key))store(key,data);
for(const name of ['blue','pink','green','yellow','purple'])store(name,materials[name]);
for(const name of ['forestGate','forestSign','creamButton'])store(name,objects[name]);
